"""
PK-PD MLP Training Script  (improved)
======================================
Trains SimpleMLP, DeepMLP, ResidualMLP, and AttentionMLP on the full dataset
(real clinical_trials.csv + synthetic data generated by generate_synthetic_data.py).

Key improvements over v1:
  • Uses all real data + synthetic augmentation (removes 1 000-sample cap)
  • 200 epochs with ReduceLROnPlateau scheduling
  • Early stopping (patience = 20)
  • Huber loss (more robust to PK outliers)
  • Gradient clipping (max_norm = 1.0)
  • Saves per-model validation results as JSON
  • Writes results/training_results.json with full metrics

Usage:
    python -m src.training.train
    python src/training/train.py
"""

import json
import os
import sys
import time
import warnings

warnings.filterwarnings("ignore")
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
import torch.nn as nn
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

from src.models.mlp_architectures import AttentionMLP, DeepMLP, ResidualMLP, SimpleMLP
from src.training.features import build_dataset


# ── Training loop ──────────────────────────────────────────────────────────────

def train_model(model, X_train, y_train, X_val, y_val,
                model_name: str,
                epochs: int = 200,
                batch_size: int = 128,
                lr: float = 3e-4,
                patience: int = 20,
                device: str = "cpu"):
    model = model.to(device)

    X_tr = torch.tensor(X_train, dtype=torch.float32).to(device)
    y_tr = torch.tensor(y_train, dtype=torch.float32).to(device)
    X_va = torch.tensor(X_val,   dtype=torch.float32).to(device)
    y_va = torch.tensor(y_val,   dtype=torch.float32).to(device)

    loader = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(X_tr, y_tr),
        batch_size=batch_size, shuffle=True, drop_last=False,
    )

    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="min", factor=0.5, patience=8, min_lr=1e-6
    )
    criterion = nn.HuberLoss(delta=0.3)   # robust to PK concentration outliers

    train_losses, val_losses = [], []
    best_val   = float("inf")
    best_state = None
    no_improve = 0
    t0 = time.time()

    for epoch in range(1, epochs + 1):
        model.train()
        ep_loss, n_batches = 0.0, 0
        for xb, yb in loader:
            optimizer.zero_grad()
            loss = criterion(model(xb), yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            optimizer.step()
            ep_loss  += loss.item()
            n_batches += 1
        train_losses.append(ep_loss / n_batches)

        model.eval()
        with torch.no_grad():
            val_loss = criterion(model(X_va), y_va).item()
        val_losses.append(val_loss)
        scheduler.step(val_loss)

        if val_loss < best_val - 1e-6:
            best_val   = val_loss
            best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            no_improve = 0
        else:
            no_improve += 1

        if epoch % 20 == 0 or epoch == 1:
            lr_now = optimizer.param_groups[0]["lr"]
            print(f"  [{model_name}] epoch {epoch:3d}/{epochs}  "
                  f"train={train_losses[-1]:.5f}  val={val_losses[-1]:.5f}  "
                  f"lr={lr_now:.2e}  no_improve={no_improve}")

        if no_improve >= patience:
            print(f"  [{model_name}] Early stop at epoch {epoch} (patience={patience})")
            break

    # Restore best checkpoint
    if best_state is not None:
        model.load_state_dict(best_state)

    model.eval()
    with torch.no_grad():
        preds_np = model(X_va).cpu().numpy()
    y_np = y_val

    flat_y = y_np.flatten()
    flat_p = preds_np.flatten()
    metrics = {
        "model":         model_name,
        "epochs_run":    len(train_losses),
        "training_sec":  round(time.time() - t0, 2),
        "best_val_loss": round(best_val, 6),
        "mse":           round(float(mean_squared_error(flat_y, flat_p)), 6),
        "mae":           round(float(mean_absolute_error(flat_y, flat_p)), 6),
        "rmse":          round(float(np.sqrt(mean_squared_error(flat_y, flat_p))), 6),
        "r2":            round(float(r2_score(flat_y, flat_p)), 4),
        "pk_r2":         round(float(r2_score(y_np[:, 0], preds_np[:, 0])), 4),
        "pd_r2":         round(float(r2_score(y_np[:, 1], preds_np[:, 1])), 4),
        "pk_mae":        round(float(mean_absolute_error(y_np[:, 0], preds_np[:, 0])), 6),
        "pd_mae":        round(float(mean_absolute_error(y_np[:, 1], preds_np[:, 1])), 6),
        "train_loss_curve": [round(v, 6) for v in train_losses],
        "val_loss_curve":   [round(v, 6) for v in val_losses],
    }
    return metrics, model


# ── Entry point ────────────────────────────────────────────────────────────────

def main():
    print("PK-PD MLP Training (v2 — full dataset + synthetic augmentation)")
    print("=" * 70)

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Device: {device}")

    data_dir = os.path.join(_ROOT, "data", "raw")

    # Check if synthetic data exists; generate if not
    syn_path = os.path.join(data_dir, "synthetic_clinical_data.csv")
    if not os.path.exists(syn_path):
        print("\nSynthetic data not found — generating 50 000 samples…")
        from src.training.generate_synthetic_data import generate_samples
        df = generate_samples(n=50_000, seed=42)
        df.to_csv(syn_path, index=False)
        print(f"  Saved {len(df):,} rows → {syn_path}")

    print("\nBuilding feature dataset (real + synthetic)…")
    X, y = build_dataset(data_dir, max_samples=None, use_synthetic=True)
    print(f"  Total: {len(X)} samples × {X.shape[1]} features")

    # Standardise inputs (fit on train, apply to val/test)
    X_tmp, X_test, y_tmp, y_test = train_test_split(
        X, y, test_size=0.10, random_state=42
    )
    X_train, X_val, y_train, y_val = train_test_split(
        X_tmp, y_tmp, test_size=0.111, random_state=42   # 0.111 of 0.90 ≈ 10 % overall
    )

    scaler = StandardScaler()
    X_train = scaler.fit_transform(X_train).astype(np.float32)
    X_val   = scaler.transform(X_val).astype(np.float32)
    X_test  = scaler.transform(X_test).astype(np.float32)

    print(f"  train={len(X_train)}  val={len(X_val)}  test={len(X_test)}")

    # Save scaler for inference
    ckpt_dir = os.path.join(_ROOT, "checkpoints")
    os.makedirs(ckpt_dir, exist_ok=True)
    import pickle
    scaler_path = os.path.join(ckpt_dir, "feature_scaler.pkl")
    with open(scaler_path, "wb") as f:
        pickle.dump(scaler, f)
    print(f"  Scaler → {scaler_path}")

    input_dim = X.shape[1]
    model_specs = {
        "simple_mlp":    SimpleMLP(input_dim=input_dim, hidden_dim=128, output_dim=2),
        "deep_mlp":      DeepMLP(input_dim=input_dim,   hidden_dim=256, output_dim=2),
        "residual_mlp":  ResidualMLP(input_dim=input_dim, hidden_dim=256, output_dim=2),
        "attention_mlp": AttentionMLP(input_dim=input_dim, hidden_dim=256, output_dim=2,
                                      dropout=0.20, n_blocks=5),
    }

    results_dir = os.path.join(_ROOT, "results")
    os.makedirs(results_dir, exist_ok=True)

    all_metrics = []
    trained     = {}

    for key, model in model_specs.items():
        n_params = sum(p.numel() for p in model.parameters())
        print(f"\n{'='*60}")
        print(f"Training {key}  ({n_params:,} parameters)…")
        metrics, trained_model = train_model(
            model, X_train, y_train, X_val, y_val,
            model_name=key,
            epochs=200,
            batch_size=256,
            lr=3e-4,
            patience=20,
            device=device,
        )
        all_metrics.append(metrics)
        trained[key] = trained_model

        ckpt_path = os.path.join(ckpt_dir, f"{key}_model.pth")
        torch.save(trained_model.state_dict(), ckpt_path)
        print(f"  → checkpoint: {ckpt_path}")
        print(f"  → R²={metrics['r2']:.4f}  PK R²={metrics['pk_r2']:.4f}  PD R²={metrics['pd_r2']:.4f}")

    # ── Test-set evaluation ────────────────────────────────────────────────────
    print(f"\n{'='*70}")
    print("HELD-OUT TEST SET EVALUATION")
    print("-" * 70)
    print(f"{'Model':<20} {'R²':>8} {'RMSE':>8} {'PK R²':>8} {'PD R²':>8} {'Epochs':>8}")
    print("-" * 70)

    X_te_t = torch.tensor(X_test, dtype=torch.float32).to(device)
    test_results = []
    for m in all_metrics:
        key   = m["model"]
        mdl   = trained[key].to(device)
        mdl.eval()
        with torch.no_grad():
            tp = mdl(X_te_t).cpu().numpy()
        flat_p = tp.flatten()
        flat_y = y_test.flatten()
        tr = {
            "model":   key,
            "test_r2":   round(float(r2_score(flat_y, flat_p)), 4),
            "test_rmse": round(float(np.sqrt(mean_squared_error(flat_y, flat_p))), 6),
            "test_pk_r2":round(float(r2_score(y_test[:, 0], tp[:, 0])), 4),
            "test_pd_r2":round(float(r2_score(y_test[:, 1], tp[:, 1])), 4),
            "test_pk_mae":round(float(mean_absolute_error(y_test[:, 0], tp[:, 0])), 6),
            "test_pd_mae":round(float(mean_absolute_error(y_test[:, 1], tp[:, 1])), 6),
            "val_r2":  m["r2"],
            "val_pk_r2": m["pk_r2"],
            "val_pd_r2": m["pd_r2"],
            "epochs_run": m["epochs_run"],
        }
        test_results.append(tr)
        print(f"  {key:<18} {tr['test_r2']:>8.4f} {tr['test_rmse']:>8.4f} "
              f"{tr['test_pk_r2']:>8.4f} {tr['test_pd_r2']:>8.4f} {tr['epochs_run']:>8}")

    # ── JSON results ────────────────────────────────────────────────────────────
    import datetime
    best_model = max(all_metrics, key=lambda m: m["r2"])
    output_json = {
        "training_date":    datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "device":           device,
        "dataset": {
            "n_train":      len(X_train),
            "n_val":        len(X_val),
            "n_test":       len(X_test),
            "feature_dim":  int(input_dim),
        },
        "hyperparameters": {
            "epochs":       200,
            "batch_size":   256,
            "lr":           3e-4,
            "optimizer":    "AdamW",
            "scheduler":    "ReduceLROnPlateau(factor=0.5, patience=8)",
            "loss":         "HuberLoss(delta=0.3)",
            "early_stop_patience": 20,
            "grad_clip":    1.0,
        },
        "models":      all_metrics,
        "test_results":test_results,
        "best_model": {
            "name":   best_model["model"],
            "val_r2": best_model["r2"],
            "val_pk_r2": best_model["pk_r2"],
            "val_pd_r2": best_model["pd_r2"],
        },
    }

    json_path = os.path.join(results_dir, "training_results.json")
    with open(json_path, "w") as f:
        json.dump(output_json, f, indent=2)
    print(f"\nValidation JSON → {json_path}")

    # ── Comparison plot ─────────────────────────────────────────────────────────
    fig, axes = plt.subplots(2, 3, figsize=(17, 9))
    names  = [m["model"]   for m in all_metrics]
    r2s    = [m["r2"]      for m in all_metrics]
    pk_r2s = [m["pk_r2"]   for m in all_metrics]
    pd_r2s = [m["pd_r2"]   for m in all_metrics]
    rmses  = [m["rmse"]    for m in all_metrics]
    maes   = [m["mae"]     for m in all_metrics]
    colors = ["#00bcd4","#ff7043","#ab47bc","#66bb6a"]

    ax = axes[0, 0]; ax.bar(names, r2s, color=colors); ax.set_title("Validation R²"); ax.tick_params(axis="x", rotation=20); ax.set_ylim(0, 1)
    ax = axes[0, 1]; ax.bar(names, rmses, color=colors); ax.set_title("Validation RMSE"); ax.tick_params(axis="x", rotation=20)
    ax = axes[0, 2]; ax.bar(names, maes, color=colors); ax.set_title("Validation MAE"); ax.tick_params(axis="x", rotation=20)

    x   = np.arange(len(names))
    ax  = axes[1, 0]
    ax.bar(x - 0.2, pk_r2s, 0.35, label="PK R²", color="#00bcd4")
    ax.bar(x + 0.2, pd_r2s, 0.35, label="PD R²", color="#ff7043")
    ax.set_xticks(x); ax.set_xticklabels(names, rotation=20)
    ax.set_title("PK vs PD R²"); ax.legend(); ax.set_ylim(0, 1)

    # Loss curves — best model
    ax  = axes[1, 1]
    best_m = max(all_metrics, key=lambda m: m["r2"])
    ax.plot(best_m["train_loss_curve"], label="train", color="#00bcd4")
    ax.plot(best_m["val_loss_curve"],   label="val",   color="#ff7043")
    ax.set_title(f"Loss curves — {best_m['model']}"); ax.legend(); ax.grid(True, alpha=0.3)
    ax.set_xlabel("Epoch"); ax.set_ylabel("Huber Loss")

    # Test R²
    ax  = axes[1, 2]
    t_pkr2 = [tr["test_pk_r2"] for tr in test_results]
    t_pdr2 = [tr["test_pd_r2"] for tr in test_results]
    ax.bar(x - 0.2, t_pkr2, 0.35, label="Test PK R²", color="#00bcd4")
    ax.bar(x + 0.2, t_pdr2, 0.35, label="Test PD R²", color="#ff7043")
    ax.set_xticks(x); ax.set_xticklabels(names, rotation=20)
    ax.set_title("Test PK vs PD R²"); ax.legend(); ax.set_ylim(0, 1)

    fig.suptitle("PK-PD MLP Comparison (v2)", fontsize=14, fontweight="bold")
    plt.tight_layout()
    plot_path = os.path.join(results_dir, "model_comparison.png")
    fig.savefig(plot_path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"Comparison plot → {plot_path}")
    print("\nDone.")


if __name__ == "__main__":
    main()
